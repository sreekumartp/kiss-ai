"""Turn the job-posting research into the app's job-market data.

Usage: python3 tools/build_jobs_data.py data/jobs-2026-11 "Nov 2026"

Reads jd-*.json (one entry per role: postings, skills mapped to topic ids, region notes, summary)
and writes the JOBS block into source/kiss-atlas.html between the JOBS-DATA markers. Topics added to the map
since the research are matched to skills by keyword and listed first; topic ids that no
longer exist are dropped. Run it again after each quarterly refresh.
"""
import glob
import json
import os
import re
import sys

src_dir, checked = sys.argv[1], sys.argv[2]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HTML = os.path.join(ROOT, "source", "kiss-atlas.html")
html = open(HTML, encoding="utf-8").read()
TOPICS = set(re.findall(r'^\s*\[\s*"([a-z0-9]+)"\s*,\s*"', html, re.M))

# Skills that were gaps during the research, now covered by topics added afterwards.
LATER = [
    (r"cuda|triton|kernel|cutlass|profil", "gpukernels"),
    (r"observab|tracing|cost.?track|token track", "llmobs"),
    (r"bedrock|vertex|azure ai|foundry|cloud ai platform|managed model", "aiplatforms"),
    (r"eu ai act|nist|iso.?42001|model risk|sr 11-7|conformity", "aicompliance"),
    (r"owasp|mitre atlas|threat model", "aithreat"),
    (r"test automation|test framework|non-determin|ci.?/?cd test|quality gate", "aitesting"),
    (r"annotation|rubric|human eval|grader", "humanannot"),
    (r"publication|reproduc|ablation|research method|paper", "mlresearch"),
    (r"\b3d\b|pose est|slam|\bvio\b|visual odometry|nerf|gaussian splat|visual locali[sz]ation", "vision3d"),
    (r"voice agent|voice interface|\bvad\b|endpointing|livekit|pipecat|streaming asr", "voiceagents"),
    (r"multilingual|low.?resource|code.?switch|indic|translitera|hinglish", "multilingual"),
    (r"controlnet|controllable|post.?training for diffusion|rl .*diffusion|diffusion.*preference", "controlgen"),
    (r"robot data|teleop|demonstration data", "robotdata"),
]

jobs = {}
for path in sorted(glob.glob(os.path.join(src_dir, "jd-*.json"))):
    for r in json.load(open(path, encoding="utf-8"))["roles"]:
        posts = r.get("postings", [])
        regions = {"US": 0, "EU": 0, "IN": 0}
        for p in posts:
            reg = (p.get("region") or "").upper()
            if reg in regions:
                regions[reg] += 1
        skills = []
        for s in r.get("skills", []):
            low = s["skill"].lower()
            later = [t for rx, t in LATER if re.search(rx, low) and t in TOPICS][:1]
            topics = later + [t for t in s.get("topics", []) if t in TOPICS and t not in later]
            count = int(s.get("count") or 0)
            if count < 1:
                continue
            skills.append({"s": s["skill"], "c": count, "r": [x for x in s.get("regions", []) if x in regions], "t": topics})
        skills.sort(key=lambda x: -x["c"])
        jobs[r["role"]] = {
            "n": len(posts),
            "reg": regions,
            "titles": r.get("title_variants", [])[:6],
            "skills": skills[:14],
            "notes": [n for n in r.get("region_specific", []) if n][:4],
            "summary": r.get("summary", ""),
            "posts": [{"t": p.get("title", ""), "c": p.get("company", ""), "l": p.get("location", ""), "r": (p.get("region") or "").upper(), "u": p.get("url", "")}
                      for p in posts if p.get("url", "").startswith("https://")],
        }

block = ("/* JOBS-DATA-START (generated by tools/build_jobs_data.py; do not edit by hand) */\n"
         f"const JOBS_CHECKED = {json.dumps(checked)};\n"
         f"const JOBS = {json.dumps(jobs, ensure_ascii=False, separators=(',', ':'))};\n"
         "/* JOBS-DATA-END */")
if "/* JOBS-DATA-START" in html:
    html = re.sub(r"/\* JOBS-DATA-START.*?/\* JOBS-DATA-END \*/", lambda m: block, html, flags=re.S)
else:
    marker = "/* ---------- Model ---------- */"
    html = html.replace(marker, block + "\n\n" + marker, 1)
open(HTML, "w", encoding="utf-8").write(html)
print(f"{len(jobs)} roles, {sum(j['n'] for j in jobs.values())} postings, {len(block)//1024} KB")
